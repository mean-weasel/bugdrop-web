#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const RECIPE_SOURCE_SHA = "a100e69976ce0a5912df8f07af1b2e53029663b2";
const RECIPE_SOURCE_BYTE_LENGTH = 8537;
const RECIPE_SOURCE_DIGEST = "ca205013c47e14cb37cc6f763439922a448d5d06c569940a8b08fc4364b0372d";
const RUNTIME_TARGET_SHA = "47a392d1e7b1a8d8adeff1692f6bbbd84696280d";
const RUNTIME_RELEASE = "v1.56.3";
const RUNTIME_BYTE_LENGTH = 238591;
const RUNTIME_DIGEST = "338cdb5b19c69dc3429fdcb8f800e3b98a3bdd442fee78563523cd731e2bdf0e";
const RUNTIME_LOCAL_PATH = `public/vendor/bugdrop/${RUNTIME_TARGET_SHA}/widget.js`;
const OUTPUT = "src/components/landing/homepage-flow-recipes.generated.ts";

function parseArguments(argv) {
  const values = new Map();

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--write" || argument === "--check") {
      if (values.has("mode")) throw new Error("Pass exactly one of --write or --check.");
      values.set("mode", argument.slice(2));
      continue;
    }
    if (argument === "--source" || argument === "--source-sha") {
      const value = argv[index + 1];
      if (!value || value.startsWith("--")) throw new Error(`Missing value for ${argument}.`);
      if (values.has(argument)) throw new Error(`Pass ${argument} only once.`);
      values.set(argument, value);
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  if (!values.has("mode")) throw new Error("Pass exactly one of --write or --check.");
  if (!values.has("--source")) throw new Error("Pass --source.");
  if (!values.has("--source-sha")) throw new Error("Pass --source-sha.");
  if (values.get("--source-sha") !== RECIPE_SOURCE_SHA) {
    throw new Error(`Unexpected source SHA: ${values.get("--source-sha")}`);
  }

  return {
    mode: values.get("mode"),
    source: values.get("--source"),
  };
}

function sha256(source) {
  return createHash("sha256").update(source).digest("hex");
}

function generatedSource(source, localPath) {
  const importLine = "import type { FlowConfig, FlowOpenOptions } from '../../src/widget/flows/public-types';\n\n";
  if (!source.startsWith(importLine)) {
    throw new Error("The canonical recipe source does not have the expected type-only SDK import.");
  }

  const transformed = source
    .slice(importLine.length)
    .replace(/\bFlowRecipeId\b/g, "HomepageFlowRecipeId")
    .replace(/\bFlowRecipe\b/g, "HomepageFlowRecipe")
    .replace(/\bFlowConfig\b/g, "HomepageFlowConfig")
    .replace(/\bFlowOpenOptions\b/g, "HomepageFlowOpenOptions")
    .replace(/\bflowRecipes\b/g, "homepageFlowRecipes")
    .replace(/\bflowRecipeList\b/g, "homepageFlowRecipeList");

  const header = `// This file is generated by scripts/vendor-homepage-flow-recipes.mjs. Do not edit.\n\nexport type HomepageFlowConfig = {\n  readonly configVersion: 1;\n  readonly id: string;\n  readonly [key: string]: unknown;\n};\n\nexport type HomepageFlowOpenOptions = {\n  readonly context?: Readonly<Record<string, string | number | boolean>>;\n};\n\nexport const HOMEPAGE_FLOW_RECIPE_SOURCE = Object.freeze({\n  sourceSha: "${RECIPE_SOURCE_SHA}",\n  localPath: "${localPath}",\n  byteLength: ${RECIPE_SOURCE_BYTE_LENGTH},\n  sha256: "${RECIPE_SOURCE_DIGEST}",\n});\n\nexport const HOMEPAGE_BUGDROP_RUNTIME = Object.freeze({\n  release: "${RUNTIME_RELEASE}",\n  targetSha: "${RUNTIME_TARGET_SHA}",\n  localPath: "${RUNTIME_LOCAL_PATH}",\n  byteLength: ${RUNTIME_BYTE_LENGTH},\n  sha256: "${RUNTIME_DIGEST}",\n});\n\n`;

  return `${header}${transformed}`;
}

async function main() {
  const { mode, source } = parseArguments(process.argv.slice(2));
  const sourcePath = path.resolve(process.cwd(), source);
  const contents = await readFile(sourcePath);

  if (contents.byteLength !== RECIPE_SOURCE_BYTE_LENGTH) {
    throw new Error(`Unexpected source byte length: ${contents.byteLength}`);
  }
  if (sha256(contents) !== RECIPE_SOURCE_DIGEST) {
    throw new Error("Unexpected source SHA-256.");
  }

  const output = generatedSource(contents.toString("utf8"), source);
  const outputPath = path.resolve(process.cwd(), OUTPUT);

  if (mode === "write") {
    await writeFile(outputPath, output);
    return;
  }

  const existing = await readFile(outputPath, "utf8");
  if (existing !== output) {
    throw new Error(`${OUTPUT} is not byte-identical to generated output.`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
